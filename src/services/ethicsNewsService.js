/**
 * 初始化内置新闻，逐条检查并补充缺失条目
 */
export async function seedDefaultNews() {
  let added = 0
  for (const item of _fallbackNews) {
    const exists = await getEthicsNewsByDate(item.date)
    if (!exists) {
      await createEthicsNews(item)
      added++
    }
  }
  return added
}

